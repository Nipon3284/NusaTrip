// ─── Formatter Helpers ─────────────────────────────────────────

export function formatRupiah(n: number): string {
  return new Intl.NumberFormat("id-ID", {
    style: "currency",
    currency: "IDR",
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(n);
}

export function formatPercentage(n: number): string {
  return `${n.toFixed(1)}%`;
}
